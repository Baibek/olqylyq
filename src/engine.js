  // ---------- graph builder (one per subject) ----------
  function makeGraph(key, raw, strands, depth) {
    const TOPICS = raw.map(([id, grade, strand, kk, ru, pre, unt, gen]) => ({ id, grade, strand, name: { kk, ru }, pre, unt: !!unt, gen }));
    const BY = Object.fromEntries(TOPICS.map(t => [t.id, t]));
    if (Object.keys(BY).length !== TOPICS.length) throw new Error('duplicate id in ' + key);
    TOPICS.forEach(t => { t.kids = []; if (!strands.includes(t.strand)) throw new Error('bad strand ' + t.strand + ' in ' + t.id); });
    TOPICS.forEach(t => t.pre.forEach(p => { if (!BY[p]) throw new Error('bad prereq ' + p + ' in ' + t.id); BY[p].kids.push(t.id); }));
    // closure up to `lim` steps (Infinity = full transitive closure)
    const reach = (id, rel, lim) => { const out = new Set(); let front = [...BY[id][rel]], d = 1; while (front.length && d <= lim) { const nxt = []; front.forEach(x => { if (!out.has(x)) { out.add(x); nxt.push(...BY[x][rel]); } }); front = nxt; d++; } return out; };
    TOPICS.forEach(t => { t.anc = reach(t.id, 'pre', Infinity); t.desc = reach(t.id, 'kids', Infinity); t.ancD = reach(t.id, 'pre', depth); t.descD = reach(t.id, 'kids', depth); });
    const ORDER = (() => { const indeg = {}; TOPICS.forEach(t => indeg[t.id] = t.pre.length); const q = TOPICS.filter(t => !t.pre.length).map(t => t.id); const out = []; while (q.length) { q.sort((a, b) => BY[a].grade - BY[b].grade); const x = q.shift(); out.push(x); BY[x].kids.forEach(k => { if (--indeg[k] === 0) q.push(k); }); } if (out.length !== TOPICS.length) throw new Error('cycle in ' + key); return out; })();
    const RANK = Object.fromEntries(ORDER.map((id, i) => [id, i]));
    const grades = [...new Set(TOPICS.map(t => t.grade))].sort((a, b) => a - b);
    return { key, TOPICS, BY, ORDER, RANK, STRANDS: strands, grades, depth };
  }
